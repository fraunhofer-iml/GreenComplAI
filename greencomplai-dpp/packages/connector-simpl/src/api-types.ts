// The slices of SIMPL responses this module actually reads.
//
// Only the fields consumed by mapping.ts are represented here. Additional
// upstream fields need no maintenance. Optional fields let incomplete
// responses produce missing values instead of crashing the import.

export type SimplOrganizationSummary = {
  id?: string;
  title?: string;
  type?: "CUSTOMER" | "SUPPLIER" | "MANUFACTURER";
};

export type SimplLocation = {
  buildingNumber?: string;
  city?: string;
  // ISO 3166-1 alpha-2, normalized per spec - but only "when recognized";
  // unrecognized values are passed through as-is.
  country?: string;
  isPrimary?: boolean;
  postal?: string;
  region?: string;
  street?: string;
  title?: string;
};

export type SimplOrganization = SimplOrganizationSummary & {
  externalId?: string;
  locations?: SimplLocation[] | null;
};

export type SimplAsset = {
  id?: string;
  externalId?: string | null;
  title?: string;
  // Free-text label ("high-pressure unit"), **not** the structured asset
  // type. The spec explicitly points out that the two are different things.
  type?: string | null;
  description?: string | null;
  serialNumber?: string | null;
  status?: "NEW" | "RUNNING" | "WARNING" | "INACTIVE" | "STOPPED";
  manufacturer?: SimplOrganizationSummary | null;
  owner?: SimplOrganizationSummary | null;
  location?: SimplLocation | null;
  // Keys are identifiers generated by SIMPL, not descriptive names. Their
  // meaning lives in the asset type - see `SimplAssetType.customFields`.
  customFields?: Record<string, unknown> | null;
  assetType?: { id?: string; title?: string } | null;
  resources?: { id?: string; name?: string; type?: string; isPublic?: boolean }[] | null;
  updatedAt?: string;
};

// The JSON schema of an asset type's custom fields. SIMPL does not fix what
// goes into `properties[key]` - hence `unknown` here and a defensive
// evaluation in mapping.ts.
export type SimplAssetType = {
  id?: string;
  title?: string;
  description?: string | null;
  customFields?: {
    properties?: Record<string, unknown>;
  } | null;
};

export type SimplPart = {
  id?: string;
  externalId?: string | null;
  name?: string;
  // Article number.
  article?: string | null;
  description?: string | null;
  storageLocation?: string | null;
  manufacturer?: SimplOrganizationSummary | null;
  updatedAt?: string;
};
