import type {
  ExternalAttribute,
  ExternalFieldType,
  ExternalIdentifier,
  ExternalOperator,
  ExternalProduct,
} from "@dpp/connector-sdk";

import type {
  SimplAsset,
  SimplAssetType,
  SimplLocation,
  SimplOrganization,
  SimplOrganizationSummary,
  SimplPart,
} from "./api-types.js";

// The SIMPL -> catalogue mapping. Pure functions without HTTP, so the actual
// translation work is testable without pretending to be an external system.
//
// Base rule: never invent anything. What matches no catalogue property becomes
// an attribute - it is not lost, but it also does not silently turn into a
// passport data element. Which dictionary entry a field follows is a domain
// decision and is not something the ERP knows.

// SIMPL knows three organization types, the standard knows seven roles. The
// mapping is deliberately cautious: a "CUSTOMER" in the manufacturer field is
// an inconsistency of the source system, not information about a role - the
// role is determined by the field the value sits in.
export function operatorRoles(type: SimplOrganizationSummary["type"]): ExternalOperator["roles"] {
  switch (type) {
    case "SUPPLIER":
      return ["distributor"];
    case "MANUFACTURER":
      return ["manufacturer"];
    default:
      return ["manufacturer"];
  }
}

function address(location: SimplLocation | undefined | null) {
  if (!location) return undefined;

  const mapped = {
    street: location.street,
    buildingNumber: location.buildingNumber,
    postalCode: location.postal,
    city: location.city,
    region: location.region,
    // Only take it over if it actually looks like an alpha-2 code. The spec
    // says unknown values are left as-is - "Deutschland" as `countryCode`
    // would be worse than none at all.
    countryCode: /^[A-Za-z]{2}$/.test(location.country ?? "")
      ? location.country?.toUpperCase()
      : undefined,
  };

  return Object.values(mapped).some(Boolean) ? mapped : undefined;
}

// The address comes from the organization record, not the summary on the
// product: the summary carries only id, title and type.
function operator(
  summary: SimplOrganizationSummary | undefined | null,
  detail?: SimplOrganization | undefined,
): ExternalOperator | undefined {
  const externalId = summary?.id ?? detail?.id;
  const legalName = summary?.title ?? detail?.title;
  if (!externalId || !legalName) return undefined;

  const locations = detail?.locations ?? [];
  const primary = locations.find((location) => location.isPrimary) ?? locations[0];

  return {
    externalId,
    legalName,
    roles: operatorRoles(summary?.type ?? detail?.type),
    address: address(primary),
  };
}

// The keys in `asset.customFields` are identifiers generated by SIMPL. Their
// meaning lives in the asset type's JSON Schema - without it, the identifier
// itself is left as the label, which is more honest than dropping the field.
export function resolveCustomFields(
  customFields: Record<string, unknown> | undefined | null,
  assetType: SimplAssetType | undefined,
): ExternalAttribute[] {
  const properties = (assetType?.customFields?.properties ?? {}) as Record<string, unknown>;

  return Object.entries(customFields ?? {})
    .filter(([, value]) => value !== undefined && value !== "")
    .map(([key, value]) => {
      const definition = (properties[key] ?? {}) as Record<string, unknown>;

      return {
        key,
        label: readString(definition.title) ?? readString(definition.description) ?? key,
        value: normaliseValue(value),
        unit: readString(definition.unit),
        // Only where the title already carries the name: repeating the title
        // as the description would fill a field without saying anything.
        description: readString(definition.title) ? readString(definition.description) : undefined,
        valueType: fieldType(definition),
        allowedValues: enumValues(definition),
      };
    });
}

// The JSON Schema type of a custom field, translated into the vocabulary the
// SDK knows. Only what the schema actually states - a field without a type is
// a field without a type, and inferring one from the current value would make
// the whole type-set depend on which asset happened to be looked up first.
//
// `enum` wins over the underlying type: that a field has a closed value list
// is the more specific statement, and it is the one a dictionary entry needs.
function fieldType(definition: Record<string, unknown>): ExternalFieldType | undefined {
  if (Array.isArray(definition.enum) && definition.enum.length > 0) return "enum";

  // A list's type is its items' type: `["mm", "cm"]` is a string field that
  // occurs several times, not a field of type "array". `array` itself says
  // nothing about the values, so it is stepped through rather than reported.
  const items = (definition.items ?? {}) as Record<string, unknown>;
  const declared = readString(definition.type);
  const inner = declared === "array" || declared === undefined;
  const type = (inner ? readString(items.type) : undefined) ?? declared;
  const format = (inner ? readString(items.format) : undefined) ?? readString(definition.format);

  switch (type) {
    case "string":
      // JSON Schema keeps dates in the format, not in the type.
      if (format === "date") return "date";
      if (format === "date-time") return "datetime";

      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    default:
      return undefined;
  }
}

function enumValues(
  definition: Record<string, unknown>,
): (string | number | boolean | null)[] | undefined {
  const values = definition.enum;
  if (!Array.isArray(values) || values.length === 0) return undefined;

  return values.map(scalarOrString);
}

function readString(value: unknown): string | undefined {
  return typeof value === "string" && value.length > 0 ? value : undefined;
}

// An attribute value is a scalar or a list of scalars. A list stays a list:
// it can still become a multi-valued data element, which a flattened string
// no longer could.
//
// Everything else - a nested object - becomes a string. That loses the shape
// but does not drop the field; and there is no single data element in the
// passport for an object structure anyway.
function normaliseValue(value: unknown): ExternalAttribute["value"] {
  if (Array.isArray(value)) {
    const scalars = value.map(scalarOrString);

    // An empty list is not a value.
    return scalars.length > 0 ? scalars : null;
  }

  return scalarOrString(value);
}

function scalarOrString(value: unknown): string | number | boolean | null {
  if (value === null || value === undefined) return null;
  if (typeof value === "string" || typeof value === "number" || typeof value === "boolean") {
    return value;
  }

  return JSON.stringify(value);
}

// Where the asset is located is not a product property - but it is
// information that lives in the ERP and would otherwise vanish on import.
function locationAttributes(location: SimplLocation | undefined | null): ExternalAttribute[] {
  if (!location) return [];

  const parts: [string, string, string | undefined][] = [
    ["location.title", "Standort", location.title],
    ["location.city", "Standort — Ort", location.city],
    ["location.country", "Standort — Land", location.country],
  ];

  return parts
    .filter(([, , value]) => Boolean(value))
    .map(([key, label, value]) => ({
      key,
      label,
      value: value ?? null,
      valueType: "string" as const,
    }));
}

// The states SIMPL's spec allows for an asset.
const ASSET_STATES = ["NEW", "RUNNING", "WARNING", "INACTIVE", "STOPPED"];

export function assetToProduct(
  asset: SimplAsset,
  options: {
    assetType?: SimplAssetType | undefined;
    manufacturer?: SimplOrganization | undefined;
  } = {},
): ExternalProduct | undefined {
  // The anchor for re-import is the external id if there is one - otherwise
  // the internal SIMPL id. Without either, a second import would have nothing
  // to recognize the same product by.
  const externalId = asset.externalId ?? asset.id;
  if (!externalId || !asset.title) return undefined;

  const identifiers: ExternalIdentifier[] = [];
  if (asset.serialNumber) {
    identifiers.push({ type: "serialNumber", value: asset.serialNumber, issuer: "simpl" });
  }
  // The free-text designation is in practice the machine's model designation
  // ("DEMO UNIT 01"), while the structured asset type names the coarse
  // class ("standard machine"). As a category it would therefore be lost -
  // as a model identifier it is exactly what it is.
  if (asset.type) {
    identifiers.push({ type: "model", value: asset.type, issuer: "simpl" });
  }

  return {
    externalId,
    // In SIMPL, the asset type is exactly what the field set is keyed on: all
    // assets of a type carry the same custom fields. So a mapping fixed once
    // applies to the whole type. Assets without a type share one common
    // mapping - they have no typed custom fields either.
    sourceType: asset.assetType?.id
      ? { key: `asset:${asset.assetType.id}`, label: asset.assetType.title ?? asset.assetType.id }
      : { key: "asset", label: "Anlage ohne Typ" },
    name: asset.title,
    description: asset.description ?? undefined,
    // The structured asset type takes precedence over the free-text
    // designation: it is the value maintained in the source system.
    category: asset.assetType?.title ?? asset.type ?? undefined,
    identifiers,
    manufacturer: operator(asset.manufacturer, options.manufacturer),
    attributes: [
      ...resolveCustomFields(asset.customFields, options.assetType),
      ...locationAttributes(asset.location),
      // The spec fixes the set of states - so it is a closed list, and saying
      // so is what lets it become an `enum` dictionary entry rather than free
      // text that happens to hold one of five words.
      ...(asset.status
        ? [
            {
              key: "status",
              label: "Zustand (SIMPL)",
              value: asset.status,
              valueType: "enum" as const,
              allowedValues: ASSET_STATES,
            },
          ]
        : []),
    ],
    documents: (asset.resources ?? [])
      .filter((resource) => Boolean(resource.id))
      .map((resource) => ({
        externalId: resource.id ?? "",
        // SIMPL does not always return a name in the asset response - real
        // records sometimes carry only an id and `isPublic`. Without a
        // fallback the document would silently disappear, and "the external
        // system has no documents" would be a wrong statement. The id is an
        // ugly label, but it is there.
        name: resource.name ?? `Dokument ${resource.id}`,
        mimeType: resource.type ?? undefined,
      })),
    updatedAt: asset.updatedAt,
  };
}

export function partToProduct(
  part: SimplPart,
  options: { manufacturer?: SimplOrganization | undefined } = {},
): ExternalProduct | undefined {
  const externalId = part.externalId ?? part.id;
  if (!externalId || !part.name) return undefined;

  const identifiers: ExternalIdentifier[] = [];
  if (part.article) {
    // The article number is the identifier the article is listed under in
    // the range - `sku` is the right type for it in the catalogue, not `model`.
    identifiers.push({ type: "sku", value: part.article, issuer: "simpl" });
  }

  return {
    externalId,
    // Articles have no typed custom fields - one type for all.
    sourceType: { key: "part", label: "Artikel" },
    name: part.name,
    description: part.description ?? undefined,
    identifiers,
    manufacturer: operator(part.manufacturer, options.manufacturer),
    attributes: part.storageLocation
      ? [{ key: "storageLocation", label: "Lagerort", value: part.storageLocation }]
      : [],
    documents: [],
    updatedAt: part.updatedAt,
  };
}
